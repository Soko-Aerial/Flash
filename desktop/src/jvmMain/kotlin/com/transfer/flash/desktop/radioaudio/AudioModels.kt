package com.transfer.flash.desktop.radioaudio

import com.transfer.flash.core.radio.link.maskBluetoothAddress

/**
 * Direction/flow of the audio endpoint.
 */
public enum class AudioEndpointKind {
    RENDER,   // Playback / Output (Speakers, Headsets)
    CAPTURE   // Recording / Input (Microphones)
}

/**
 * Windows Core Audio (WASAPI) endpoint state flags.
 * Corresponds to DEVICE_STATE_* constants in mmdeviceapi.h.
 */
public enum class AudioEndpointState(public val mask: Int) {
    ACTIVE(0x00000001),
    DISABLED(0x00000002),
    NOT_PRESENT(0x00000004),
    UNPLUGGED(0x00000008),
    UNKNOWN(0x00000000);

    public companion object {
        public fun fromMask(mask: Int): AudioEndpointState = when (mask) {
            0x1 -> ACTIVE
            0x2 -> DISABLED
            0x4 -> NOT_PRESENT
            0x8 -> UNPLUGGED
            else -> UNKNOWN
        }
    }
}

/**
 * Functional category of the audio device for radio gateway analysis.
 */
public enum class AudioDeviceClassification {
    RADIO_HANDS_FREE,     // Confirmed or candidate hardware radio Hands-Free endpoint (e.g. VR-N76, UV-Pro)
    BLUETOOTH_HANDS_FREE, // Other Bluetooth Hands-Free / Telephony audio endpoint (HFP/HSP)
    BLUETOOTH_STEREO,     // Bluetooth A2DP stereo playback endpoint
    SYSTEM_AUDIO          // Built-in audio, Realtek, USB soundcard, virtual cable, etc.
}

/**
 * Details of a JDK Sound mixer (javax.sound.sampled).
 */
public data class JdkMixerInfo(
    val name: String,
    val description: String,
    val vendor: String,
    val version: String,
    val isRender: Boolean,
    val isCapture: Boolean,
    val maxSourceLines: Int,
    val maxTargetLines: Int
)

/**
 * Normalized representation of an audio endpoint.
 */
public data class AudioEndpointInfo(
    val id: String,
    val name: String,
    val description: String,
    val kind: AudioEndpointKind,
    val state: AudioEndpointState,
    val classification: AudioDeviceClassification,
    val isBluetoothAssociated: Boolean,
    val bluetoothAddressFormatted: String? = null, // e.g. "38:D2:00:01:35:B5"
    val isConnectable: Boolean,
    val diagnosisNote: String
) {
    val maskedBluetoothAddress: String?
        get() = bluetoothAddressFormatted?.let { maskBluetoothAddress(it) }
}

/**
 * Comprehensive report generated by the RadioAudioProbe tool.
 */
public data class RadioAudioProbeReport(
    val timestampUtc: String,
    val jdkMixers: List<JdkMixerInfo>,
    val windowsEndpoints: List<AudioEndpointInfo>,
    val radioAudioEndpointsFound: List<AudioEndpointInfo>,
    val anyRadioEndpointActive: Boolean,
    val generalDiagnosis: String,
    val recommendation: String
)
