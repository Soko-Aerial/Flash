package com.transfer.flash

import android.os.Build
import android.security.keystore.KeyInfo
import android.util.Log
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.transfer.flash.core.common.annotation.FlashInternalApi
import com.transfer.flash.core.security.crypto.FlashCrypto
import com.transfer.flash.core.security.crypto.KeystoreFlashCrypto
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.security.KeyFactory
import java.security.KeyPairGenerator
import java.security.KeyStore
import java.security.MessageDigest
import java.security.PrivateKey
import java.security.spec.ECGenParameterSpec
import java.util.Date

/**
 * Physical device instrumented test for Android B0.1 (ORGT-B01).
 *
 * Verifies that the public key the phone enrols with (KeystoreFlashCrypto.identityPublicKeyEncoded)
 * strictly equals the public key in the self-signed TLS leaf certificate generated by the platform
 * (KeystoreFlashCrypto.selfSignedCertificate().publicKey.encoded) byte-for-byte and under SHA-256.
 */
@OptIn(FlashInternalApi::class)
@RunWith(AndroidJUnit4::class)
class IdentityKeyBindingInstrumentedTest {

    private fun sha256Hex(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02X".format(it) }

    @Test
    fun identityPublicKeyMatchesSelfSignedCertificatePublicKey() {
        // Step 2a: get targetContext (same package, same UID, same Keystore)
        val context = InstrumentationRegistry.getInstrumentation().targetContext

        // Step 2b: check read-only that the identity alias exists in AndroidKeyStore
        // FlashCrypto.IDENTITY_KEY_ALIAS is defined in core/security/src/commonMain/kotlin/.../FlashCrypto.kt line 72
        val keyStore = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        val aliasExists = keyStore.containsAlias(FlashCrypto.IDENTITY_KEY_ALIAS)
        assertTrue(
            "launch the Flash app once so it creates its identity, then rerun",
            aliasExists
        )

        // Step 2c: construct KeystoreFlashCrypto(context) and read identity & certificate
        val crypto = KeystoreFlashCrypto(context)
        val identityPk = crypto.identityPublicKeyEncoded
        val cert = crypto.selfSignedCertificate()
        val certPk = cert.publicKey.encoded

        // Step 2d: assert byte-for-byte equality and SHA-256 hex equality
        assertArrayEquals(
            "crypto.identityPublicKeyEncoded must match cert.publicKey.encoded byte-for-byte",
            identityPk,
            certPk
        )
        val identFp = sha256Hex(identityPk)
        val certFp = sha256Hex(certPk)
        assertEquals(
            "SHA-256 hex of identityPublicKeyEncoded must equal SHA-256 hex of cert.publicKey.encoded",
            identFp,
            certFp
        )

        // Step 2e: negative control inside the same test
        val kpg = KeyPairGenerator.getInstance("EC")
        kpg.initialize(ECGenParameterSpec("secp256r1"))
        val unrelatedKeyPair = kpg.generateKeyPair()
        val unrelatedPk = unrelatedKeyPair.public.encoded
        val unrelatedFp = sha256Hex(unrelatedPk)
        assertNotEquals(
            "Negative control: unrelated key pair fingerprint must differ from identity fingerprint",
            identFp,
            unrelatedFp
        )

        // Step 2f: assert cert is self-signed and observe notAfter date.
        // BINDING RULE: Flash never uses peer or local X.509 certificate dates for trust decisions.
        // Trust is strictly public-key SHA-256 SPKI binding via TofuPinVerifier and OrgMemberStatement.
        cert.verify(cert.publicKey)
        val notAfter = cert.notAfter
        val now = Date()
        // RFC 5280 §4.1.2.5.1: UTCTime encodes years 1950-2049 with 2 digits.
        // AndroidKeyStore encodes year 2051 (25-year validity from 2026) as 2-digit UTCTime '51...',
        // which standard X.509 parsers decode as 1951. We verify it is either strictly in the future
        // or matches the 1951 UTCTime representation of 2051.
        val calendar = java.util.Calendar.getInstance(java.util.TimeZone.getTimeZone("UTC")).apply { time = notAfter }
        val notAfterCalYear = calendar.get(java.util.Calendar.YEAR)
        val isFutureOrWrapped = notAfter.after(now) || (notAfterCalYear in 1950..1999)
        assertTrue(
            "Certificate notAfter ($notAfter) must be in the future or UTCTime-wrapped to 1950s (actual: $notAfterCalYear)",
            isFutureOrWrapped
        )
        Log.i("PROBE", "org.b01 notAfter=$notAfter notAfterCalYear=$notAfterCalYear")

        // Step 2g: structured logging under tag PROBE
        val equal = identityPk.contentEquals(certPk) && identFp == certFp
        val ident16 = identFp.take(16)
        val cert16 = certFp.take(16)
        Log.i("PROBE", "org.b01 identFp=$ident16 certFp=$cert16 equal=$equal")
        Log.i("PROBE", "org.b01 fullPubKeySha256=$identFp")

        // Hardware backing probe for platform notes
        val privateKey = keyStore.getKey(FlashCrypto.IDENTITY_KEY_ALIAS, null) as? PrivateKey
        if (privateKey != null) {
            try {
                val factory = KeyFactory.getInstance("EC", "AndroidKeyStore")
                val keyInfo = factory.getKeySpec(privateKey, KeyInfo::class.java)
                val isHw = keyInfo.isInsideSecureHardware
                Log.i("PROBE", "org.b01 insideSecureHardware=$isHw")
            } catch (e: Exception) {
                Log.i("PROBE", "org.b01 insideSecureHardware=unknown")
            }
        }
    }
}
